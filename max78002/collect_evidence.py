"""
collect_evidence.py
===================
Reads the output of the Analog Devices toolchain and writes the evidence required by
report section 6 (MAX78002 deployment feasibility):

    synthesis_output/synthesis_summary.md   human-readable summary (copy it into the report)
    synthesis_output/synthesis_summary.json same information for scripts

It looks at
    * the generated C project  (synthesis_output/ecg_mitbih/: cnn.c, cnn.h, main.c, weights.h, log.txt)
    * the console logs of quantize.py and ai8xize.py (if you saved them with tee)
    * model_configuration/model_summary.json (layers and parameters, written by export_ai8x.py)

Synthesis counts as PASSED only if all expected C files exist and no error is found in the logs.

Usage:
    python collect_evidence.py                     (run from the max78002 folder)
    python collect_evidence.py --synth-dir synthesis_output/ecg_mitbih
"""

import os
import re
import json
import argparse

EXPECTED_FILES = ['cnn.c', 'cnn.h', 'main.c', 'weights.h', 'sampledata.h', 'sampleoutput.h']


def read(path):
    try:
        with open(path, errors='replace') as f:
            return f.read()
    except OSError:
        return ''


def parse_summary(text):
    """Parse the 'SUMMARY OF OPS' and 'RESOURCE USAGE' blocks written by ai8xize."""
    out = {'ops_total': None, 'macc_total': None, 'layers': [], 'weight_used': None, 'weight_total': None,
           'bias_used': None, 'bias_total': None}
    m = re.search(r'Hardware:\s*([\d,]+) ops \(([\d,]+) macc', text)
    if m:
        out['ops_total'], out['macc_total'] = int(m.group(1).replace(',', '')), int(m.group(2).replace(',', ''))
    for lm in re.finditer(r'Layer (\d+):\s*([\d,]+) ops \(([\d,]+) macc', text):
        out['layers'].append({'layer': int(lm.group(1)), 'ops': int(lm.group(2).replace(',', '')),
                              'macc': int(lm.group(3).replace(',', ''))})
    m = re.search(r'Weight memory:\s*([\d,]+) bytes out of ([\d,]+) bytes', text)
    if m:
        out['weight_used'], out['weight_total'] = int(m.group(1).replace(',', '')), int(m.group(2).replace(',', ''))
    m = re.search(r'Bias memory:\s*([\d,]+) bytes out of ([\d,]+) bytes', text)
    if m:
        out['bias_used'], out['bias_total'] = int(m.group(1).replace(',', '')), int(m.group(2).replace(',', ''))
    return out


def parse_quant_log(text):
    rows = []
    for m in re.finditer(r'^(\S+\.op\.(?:weight|bias)) avg_max: ([\d.eE+-]+) max: ([\d.eE+-]+).*?bits: (\d+)', text, re.M):
        rows.append({'tensor': m.group(1), 'max': float(m.group(3)), 'bits': int(m.group(4))})
    return rows


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser(description='Collect MAX78002 toolchain evidence')
    ap.add_argument('--synth-dir', default=os.path.join(here, 'synthesis_output', 'ecg_mitbih'))
    ap.add_argument('--synth-console-log', default=os.path.join(here, 'synthesis_output', 'ai8xize_console.log'))
    ap.add_argument('--quant-log', default=os.path.join(here, 'quantization_output', 'quantize_console.log'))
    ap.add_argument('--model-summary', default=os.path.join(here, 'model_configuration', 'model_summary.json'))
    ap.add_argument('--out-dir', default=os.path.join(here, 'synthesis_output'))
    args = ap.parse_args()

    present = {f: os.path.exists(os.path.join(args.synth_dir, f)) for f in EXPECTED_FILES}
    console = read(args.synth_console_log)
    logtxt = read(os.path.join(args.synth_dir, 'log.txt'))
    main_c = read(os.path.join(args.synth_dir, 'main.c'))
    summary = parse_summary(logtxt or main_c or console)
    problems = [f'missing file: {f}' for f, ok in present.items() if not ok]
    for name, txt in [('synthesis console log', console), ('quantization log', read(args.quant_log))]:
        if re.search(r'Traceback|ERROR|Error:', txt):
            problems.append(f'error text found in {name}')
    passed = not problems and summary['weight_used'] is not None

    model = {}
    if os.path.exists(args.model_summary):
        with open(args.model_summary) as f:
            model = json.load(f)
    quant = parse_quant_log(read(args.quant_log))

    result = {'synthesis_passed': passed, 'problems': problems, 'generated_files': present, **summary,
              'model': {k: model.get(k) for k in ('input_shape', 'output', 'parameters_deployed', 'weight_bytes_int8',
                                                  'estimated_peak_activation_bytes_int8')},
              'quantization_tensors': quant}
    os.makedirs(args.out_dir, exist_ok=True)
    with open(os.path.join(args.out_dir, 'synthesis_summary.json'), 'w') as f:
        json.dump(result, f, indent=2)

    L = ['# MAX78002 synthesis summary (generated by collect_evidence.py)\n',
         f"**Synthesis result: {'PASSED' if passed else 'FAILED'}**\n"]
    if problems:
        L += ['Problems: ' + '; '.join(problems) + '\n']
    L += ['## Generated C project\n', '| File | Present |', '|---|---|'] + [f'| {f} | {"yes" if ok else "NO"} |' for f, ok in present.items()]
    L.append('')
    if model:
        L += ['## Model', f"* Input: {model.get('input_shape')} (channels x samples), output: {model.get('output')} classes",
              f"* Parameters stored on the chip (8-bit weights + biases): {model.get('parameters_deployed'):,}",
              f"* Estimated peak activation memory (8-bit, input + output of one layer): {model.get('estimated_peak_activation_bytes_int8'):,} bytes (estimate)", '']
    L.append('## Resources reported by ai8xize')
    if summary['weight_used'] is not None:
        L += [f"* Weight memory: {summary['weight_used']:,} bytes of {summary['weight_total']:,} bytes "
              f"({100 * summary['weight_used'] / summary['weight_total']:.1f}%)",
              f"* Bias memory: {summary['bias_used']:,} bytes of {summary['bias_total']:,} bytes "
              f"({100 * summary['bias_used'] / summary['bias_total']:.1f}%)",
              f"* Operations per inference: {summary['ops_total']:,} ({summary['macc_total']:,} multiply-accumulate)", '',
              '| Layer | Operations | MACC |', '|---|---|---|']
        L += [f"| {r['layer']} | {r['ops']:,} | {r['macc']:,} |" for r in summary['layers']]
    else:
        L.append('(resource summary not found: check that log.txt / main.c exist in the synthesis folder)')
    L += ['', '## Quantization (8-bit) tensors from quantize.py']
    if quant:
        L += ['| Tensor | Largest absolute value before quantization | Bits |', '|---|---|---|'] + \
             [f"| {r['tensor']} | {r['max']:.4f} | {r['bits']} |" for r in quant]
    else:
        L.append('(quantize console log not found)')
    L += ['', '## Not measured', 'No MAX78002 board is used in this project, so real latency, energy and RAM use are not measured. '
          'The operation count above is a simulation-level quantity only.']
    with open(os.path.join(args.out_dir, 'synthesis_summary.md'), 'w') as f:
        f.write('\n'.join(L))
    print('\n'.join(L))


if __name__ == '__main__':
    main()
