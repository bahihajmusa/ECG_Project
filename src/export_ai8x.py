import numpy as np
import torch
from torch.utils.data import Dataset

import ai8x

CLASS_NAMES = ('N', 'S', 'V', 'F')
# class weights = total / (4 * count) from the TRAINING set (written by export_ai8x.py from class_weights.json)
CLASS_WEIGHTS = __CLASS_WEIGHTS__


class ECGBeats(Dataset):
    """Prepared beats; x in [-1, 1] is mapped to [0, 1] so ai8x.normalize gives 8-bit values."""

    def __init__(self, X, y, augment_mask, transform):
        self.X = X.astype(np.float32)
        self.y = y.astype(np.int64)
        self.augment_mask = augment_mask          # True for beats that may be augmented (training only)
        self.transform = transform

    def __len__(self):
        return len(self.X)

    def _augment(self, x):
        x = x * np.random.uniform(0.9, 1.1)                                   # gain
        s = np.random.randint(-3, 4)                                          # small time shift
        if s != 0:
            x2 = np.roll(x, s)
            if s > 0:
                x2[:s] = x[0]
            else:
                x2[s:] = x[-1]
            x = x2
        t = np.arange(len(x)) / 360.0                                         # baseline wander
        x = x + np.random.uniform(0, 0.1) * (np.ptp(x) + 1e-10) * np.sin(
            2 * np.pi * np.random.uniform(0.1, 0.5) * t + np.random.uniform(0, 2 * np.pi))
        x = x + np.random.normal(0, 0.02 * max(np.std(x), 0.01), size=x.shape)  # sensor noise
        return np.clip(x, -1.0, 1.0)

    def __getitem__(self, idx):
        x = self.X[idx].copy()
        if self.augment_mask[idx]:
            x = self._augment(x).astype(np.float32)
        x01 = torch.from_numpy((x + 1.0) / 2.0).unsqueeze(0)                 # (1, 360) in [0, 1]
        if self.transform is not None:
            x01 = self.transform(x01)                                         # -> [-128, 127] / 128
        return x01, torch.tensor(self.y[idx], dtype=torch.long)


def _load(root, split):
    return (np.load(os.path.join(root, f'X_{split}.npy')), np.load(os.path.join(root, f'y_{split}.npy')))


def ecg_mitbih_get_datasets(data, load_train=True, load_test=True, aug=None):  # pylint: disable=unused-argument
    """Called by ai8x-training. `data` = (data_dir, args)."""
    data_dir, args = data
    root = os.path.join(data_dir, 'ECG_MITBIH')
    transform = ai8x.normalize(args=args)

    train_dataset = test_dataset = None
    if load_train:
        Xtr, ytr = _load(root, 'train')
        Xva, yva = _load(root, 'val')
        X = np.concatenate([Xtr, Xva])
        y = np.concatenate([ytr, yva])
        augment = np.concatenate([np.ones(len(Xtr), bool), np.zeros(len(Xva), bool)])   # never augment validation
        train_dataset = ECGBeats(X, y, augment, transform)
        train_dataset.valid_indices = list(range(len(Xtr), len(Xtr) + len(Xva)))        # validation BY RECORD
    if load_test:
        split = 'test' if os.environ.get('ECG_TEST_SET', 'val').lower() in ('ds2', 'test') else 'val'
        Xte, yte = _load(root, split)
        test_dataset = ECGBeats(Xte, yte, np.zeros(len(Xte), bool), transform)
        print(f'[ECG_MITBIH] evaluation ("test") set = {"DS2 (FINAL TEST)" if split == "test" else "validation records"}')
    return train_dataset, test_dataset


