"""
Dataset of prepared MIT-BIH heartbeats (360 samples, 1 channel, classes N S V F).

Rules that keep the project honest:
  * The training dataset contains the TRAINING records plus the VALIDATION records. The validation
    beats are marked with `valid_indices`, so ai8x-training validates on them (split BY RECORD,
    never random beats).
  * The "test" dataset that ai8x-training evaluates is the VALIDATION set by default. The final
    test set DS2 is only used when you set the environment variable ECG_TEST_SET=ds2
    (do this once, at the very end).
  * Augmentation (gain, small shift, baseline wander, noise) is applied to TRAINING beats only.
"""
