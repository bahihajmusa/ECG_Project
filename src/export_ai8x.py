# ----------------------------------------------------------------------------
# ai8x-synthesis network YAML
# ----------------------------------------------------------------------------

def make_network_yaml(model) -> str:
    def mask(n):               # n input channels -> the n lowest processors
        return f'0x{(1 << n) - 1:016x}'
    return _dump_layers(model, ['0x2000', '0x0000'], mask)


def _dump_layers(model, offsets, mask) -> str:
    out = ['---',
           '# GENERATED by src/export_ai8x.py - network description for ai8x-synthesis (MAX78002)',
           f'arch: {MODEL_NAME}',
           f'dataset: {DATASET_NAME}',
           '',
           '# "processors" selects the processors that hold the INPUT channels of each layer.',
           '# Output offsets alternate (0x2000 / 0x0000) so a layer never overwrites its own input.',
           'layers:']
    for i, b in enumerate(model.blocks):
        items = []
        if b.pool_size > 1:
            items += [('max_pool', b.pool_size), ('pool_stride', b.pool_size)]
        items += [('pad', b.pad), ('activate', 'ReLU'), ('out_offset', offsets[i % 2]),
                  ('processors', mask(b.conv.in_channels))]
        if i == 0:
            items.append(('data_format', 'HWC'))
        items += [('operation', 'Conv1d'), ('kernel_size', b.kernel)]
        out.append(f'  # Layer {i}: conv{i + 1} ({b.conv.in_channels} -> {b.conv.out_channels} channels)')
        for j, (k, v) in enumerate(items):
            out.append(f"  {'- ' if j == 0 else '  '}{k}: {v}")
    last = len(model.blocks)
    out += [f'  # Layer {last}: fc (flatten {model.flat_features} features -> {model.num_classes} classes)',
            f'  - out_offset: {offsets[last % 2]}',
            f'    processors: {mask(model.blocks[-1].conv.out_channels)}',
            '    operation: MLP',
            '    flatten: true',
            '    output_width: 32          # wide output: raw 32-bit scores (argmax = class)',
            '']
    return '\n'.join(out)


