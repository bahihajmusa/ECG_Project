def fill(template: str, **kw) -> str:
    for k, v in kw.items():
        template = template.replace(f'__{k}__', str(v))
    return template


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        f.write(text)
    return path


def main():
    ap = argparse.ArgumentParser(description='Generate MAX78002 (ai8x) files from the model definition')
    ap.add_argument('--config', default='../configs/edge_cnn.yaml')
    ap.add_argument('--out', default='../max78002')
    ap.add_argument('--epochs', type=int, default=100, help='ai8x-training epochs (FP32 + QAT)')
    ap.add_argument('--qat-start', type=int, default=60, help='epoch where quantization-aware training starts')
    ap.add_argument('--class-weights', nargs=4, type=float, default=None, metavar='W',
                    help='override class weights N S V F (default: read class_weights.json)')
    args = ap.parse_args()

    cfg = load_config(args.config)
    base = os.path.dirname(os.path.abspath(args.config))
    processed = os.path.normpath(os.path.join(base, cfg['paths']['processed_dir']))
    out = args.out if os.path.isabs(args.out) else os.path.normpath(os.path.join(base, args.out))
    mc = os.path.join(out, 'model_configuration')

    model = build_model(cfg['model'])
    chk = check_max78002_constraints(model)
    if not chk['ok']:
        sys.exit(f"Model violates MAX78002 rules: {chk['problems']}")

    # class weights from the training set (prepare_data.py)
    cw_path = os.path.join(processed, 'class_weights.json')
    if args.class_weights:
        weights = tuple(round(w, 4) for w in args.class_weights)
    elif os.path.exists(cw_path):
        with open(cw_path) as f:
            cw = json.load(f)
        power = cfg['training'].get('class_weight_power', 1.0)
        weights = tuple(round(float(cw[str(i)]) ** power, 4) for i in range(4))
    else:
        weights = (1.0, 1.0, 1.0, 1.0)
        print('WARNING: class_weights.json not found, using equal weights. Run prepare_data.py first.')

    paths = [
        write(os.path.join(mc, 'models', MODEL_FILE), make_model_file(model, cfg['model'].get('dropout', 0.0))),
        write(os.path.join(mc, 'networks', NETWORK_YAML), make_network_yaml(model)),
        write(os.path.join(mc, 'datasets', 'ecg_mitbih.py'), DATASET_TEMPLATE.replace('__CLASS_WEIGHTS__', repr(weights))),
        write(os.path.join(mc, 'policies', 'schedule_ecg.yaml'), fill(SCHEDULE_YAML, M1=int(args.epochs * 0.5), M2=int(args.epochs * 0.75),
                                                                        M3=int(args.epochs * 0.9), EPOCHS=args.epochs)),
        write(os.path.join(mc, 'policies', 'qat_policy_ecg.yaml'), fill(QAT_YAML, START=args.qat_start)),
        write(os.path.join(mc, 'scripts', 'train_ecg.sh'), fill(TRAIN_SH, EPOCHS=args.epochs, MODEL=MODEL_NAME, DATASET=DATASET_NAME)),
        write(os.path.join(mc, 'scripts', 'quantize_ecg.sh'), QUANTIZE_SH),
        write(os.path.join(mc, 'scripts', 'evaluate_ecg.sh'), fill(EVAL_SH, MODEL=MODEL_NAME, DATASET=DATASET_NAME)),
        write(os.path.join(mc, 'scripts', 'synthesize_ecg.sh'), fill(SYNTH_SH, YAML=NETWORK_YAML)),
    ]

    # sample input: first VALIDATION beat as int64 in [-128, 127], shape (channels, length)
    xv = os.path.join(processed, 'X_val.npy')
    if os.path.exists(xv):
        beat = np.load(xv)[0]
        sample = np.clip(np.round(beat * 128.0), -128, 127).astype(np.int64).reshape(1, -1)
        os.makedirs(mc, exist_ok=True)
        np.save(os.path.join(mc, 'sample_input.npy'), sample)
        paths.append(os.path.join(mc, 'sample_input.npy'))
    else:
        print('NOTE: X_val.npy not found; sample_input.npy not created (run prepare_data.py first).')

    summary = {
        'model_file': MODEL_FILE, 'model_name': MODEL_NAME, 'dataset': DATASET_NAME,
        'input_shape': [model.in_channels, model.input_length], 'output': model.num_classes,
        'layers': describe_architecture(model),
        'parameters_deployed': count_parameters(model, True),
        'parameters_trainable_with_bn': count_parameters(model, False),
        'weight_bytes_int8': chk['weight_bytes_int8'],
        'estimated_peak_activation_bytes_int8': max(
            (r_in + r_out) for r_in, r_out in _activation_sizes(model)),
        'pre_check': chk,
    }
    write(os.path.join(mc, 'model_summary.json'), json.dumps(summary, indent=2))
    print('Generated:')
    for p in paths + [os.path.join(mc, 'model_summary.json')]:
        print('  ', os.path.relpath(p, os.getcwd()))
    print(f"Parameters (deployed): {summary['parameters_deployed']:,} | INT8 weight bytes: {summary['weight_bytes_int8']:,} | "
          f"estimated peak activations: {summary['estimated_peak_activation_bytes_int8']:,} bytes")


def _activation_sizes(model):
    """(input bytes, output bytes) of every layer for 8-bit activations (an estimate, not the chip's exact layout)."""
    ch, length, res = model.in_channels, model.input_length, []
    for b in model.blocks:
        in_bytes = ch * length
        if b.pool_size > 1:
            length //= b.pool_size
        ch = b.conv.out_channels
        res.append((in_bytes, ch * length))
    res.append((ch * length, model.num_classes * 4))      # wide output: 4 bytes per class
    return res


if __name__ == '__main__':
    main()
